const LANG_KEY = 'khata:lang'

export function translate(lang, key, vars = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`))
}

function initialLang() {
  const saved = readJSON(LANG_KEY, null)
  if (saved === 'en' || saved === 'hi') return saved
  return globalThis.navigator?.language?.toLowerCase().startsWith('hi') ? 'hi' : 'en'
}

const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k, v) => translate('en', k, v) })

export function LangProvider({ children, lang: forced }) {
  const [lang, setLangState] = useState(() => forced || initialLang())
  const setLang = useCallback((next) => {
    setLangState(next)
    writeJSON(LANG_KEY, next)
  }, [])
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])
  const value = useMemo(() => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }), [lang, setLang])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export const useT = () => useContext(LangContext)
